#!/usr/bin/env python3
"""Portable CI/release commands, invoked through bootstrap.py (Python 3.11+).

`ci` lints, tests, builds and packages one release ZIP for a native target;
`release` only builds and packages. The C++ parity oracles and the private
image set are not needed here: the Windows gate job in .github/workflows/ci.yml
runs those through `bootstrap.py t`.
"""

from __future__ import annotations

import argparse
import os
import re
import stat
import subprocess
import sys
import tempfile
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TARGETS = {
    "x86_64-pc-windows-msvc": "windows-x86_64",
    "x86_64-unknown-linux-gnu": "linux-x86_64",
    "aarch64-apple-darwin": "macos-aarch64",
}
# The Linux ZIP is built on ubuntu-22.04 and must not need a newer glibc.
GLIBC_MAX = (2, 35)
# Shipped next to the binary in every ZIP.
DOCS = ("README.md", "LICENSE", "THIRD-PARTY-NOTICES.md")
# Generated by `cargo about` and shipped next to DOCS.
LICENSES = "THIRD-PARTY-LICENSES.html"
# A committed C++-written file the packaged binary must read.
SMOKE_EXR = ROOT / "crates" / "exr-core" / "tests" / "parity" / "golden.exr"


def run(command: list[str], env: dict[str, str] | None = None, **kwargs):
    print("+ " + " ".join(map(str, command)), flush=True)
    return subprocess.run(command, cwd=ROOT, env=env, check=True, **kwargs)


def rust_host() -> str:
    output = run(["rustc", "-vV"], capture_output=True, text=True).stdout
    return next(line.removeprefix("host: ") for line in output.splitlines()
                if line.startswith("host: "))


def build_env(target: str) -> dict[str, str]:
    env = os.environ.copy()
    if target.endswith("windows-msvc"):
        # No VC++ redistributable on the user's machine: link the CRT statically.
        env["RUSTFLAGS"] = (env.get("RUSTFLAGS", "") + " -C target-feature=+crt-static").strip()
    # Cargo gives CARGO_ENCODED_RUSTFLAGS precedence over RUSTFLAGS.
    env.pop("CARGO_ENCODED_RUSTFLAGS", None)
    # Separate from the developer's target/: the static-CRT flags rebuild everything.
    env["CARGO_TARGET_DIR"] = str(ROOT / "target" / "portable")
    # Full debug info for the whole test build overflows a hosted runner's disk (~14 GB
    # free on Linux); line tables keep backtraces readable at a fraction of the size.
    env["CARGO_PROFILE_DEV_DEBUG"] = "line-tables-only"
    # Tests on the C++ oracle skip here instead of failing; the gate job runs them.
    env["EXR_ALLOW_SKIP"] = "1"
    return env


def verify_dependencies(binary: Path, target: str) -> None:
    """Fail unless the binary loads on a clean machine: system libraries only."""
    if target.endswith("windows-msvc"):
        sysroot = Path(run(["rustc", "--print", "sysroot"], capture_output=True,
                           text=True).stdout.strip())
        readobj = sysroot / "lib" / "rustlib" / rust_host() / "bin" / "llvm-readobj.exe"
        output = run([str(readobj), "--coff-imports", str(binary)],
                     capture_output=True, text=True).stdout
        imports = re.findall(r"Name: (\S+\.dll)", output, re.IGNORECASE)
        if not imports:
            raise RuntimeError("LLVM returned no PE imports")
        forbidden = ("vcruntime", "msvcp", "ucrtbase", "api-ms-win-crt")
        if any(name.lower().startswith(forbidden) for name in imports):
            raise RuntimeError(f"non-portable Windows imports: {imports}")
        print(f"Windows imports: {', '.join(imports)}", flush=True)
    elif "linux" in target:
        output = run(["readelf", "--version-info", str(binary)],
                     capture_output=True, text=True).stdout
        versions = [tuple(map(int, version.split(".")))
                    for version in re.findall(r"GLIBC_(\d+(?:\.\d+)+)", output)]
        if not versions or max(versions) > GLIBC_MAX:
            raise RuntimeError(f"binary requires glibc newer than {GLIBC_MAX}: {max(versions, default=None)}")
        dynamic = run(["readelf", "--dynamic", str(binary)],
                      capture_output=True, text=True).stdout
        libraries = re.findall(r"\(NEEDED\).*\[(.*?)\]", dynamic)
        # The GPU, window and Vulkan libraries are loaded at run time (dlopen), not linked.
        allowed = {"libc.so.6", "libm.so.6", "libdl.so.2", "libpthread.so.0",
                   "librt.so.1", "libgcc_s.so.1", "ld-linux-x86-64.so.2"}
        if not libraries or set(libraries) - allowed:
            raise RuntimeError(f"unexpected Linux dependencies: {libraries}")
        print(f"Linux glibc baseline: {'.'.join(map(str, max(versions)))}; needs {libraries}", flush=True)
    else:
        output = run(["otool", "-L", str(binary)], capture_output=True, text=True).stdout
        libraries = [line.strip().split(" (", 1)[0] for line in output.splitlines()[1:]]
        if not libraries or any(not name.startswith(("/usr/lib/", "/System/Library/"))
                                for name in libraries):
            raise RuntimeError(f"non-system macOS dependencies: {libraries}")


def licenses(target: str, env: dict[str, str]) -> Path:
    """Render the license texts of every crate in the binary (about.toml, about.hbs).

    MIT, Apache-2.0, BSD and LGPL all require their texts to ship with a binary; a
    license missing from about.toml's `accepted` list fails the release.
    """
    output = Path(env["CARGO_TARGET_DIR"]) / LICENSES
    run(["cargo", "about", "generate", "--locked", "--fail", "--target", target,
         "--output-file", str(output), "about.hbs"], env)
    return output


def package(binary: Path, target: str, version: str, licenses: Path) -> Path:
    destination = ROOT / "dist" / f"exr-rs-v{version}-{TARGETS[target]}.zip"
    destination.parent.mkdir(parents=True, exist_ok=True)
    payload = {binary.name: binary, **{name: ROOT / name for name in DOCS},
               LICENSES: licenses}
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9) as archive:
        for name, source in payload.items():
            entry = zipfile.ZipInfo(name)
            entry.create_system = 3
            mode = 0o755 if name == binary.name else 0o644
            entry.external_attr = (stat.S_IFREG | mode) << 16
            entry.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(entry, source.read_bytes())
    with zipfile.ZipFile(destination) as archive:
        if archive.namelist() != list(payload) or archive.testzip() is not None:
            raise RuntimeError("release ZIP failed verification")
        with tempfile.TemporaryDirectory(prefix="exr-rs-release-") as directory:
            archive.extractall(directory)
            extracted = Path(directory) / binary.name
            extracted.chmod(0o755)
            # An empty PATH: the binary must start without any build-time DLL directory.
            env = os.environ.copy()
            env["PATH"] = ""
            for key in ("LD_LIBRARY_PATH", "DYLD_LIBRARY_PATH"):
                env.pop(key, None)
            output = subprocess.run([str(extracted), "--version"], cwd=directory, env=env,
                                    check=True, capture_output=True, text=True,
                                    timeout=30).stdout.strip()
            if output != f"exr-rs {version}":
                raise RuntimeError(f"unexpected binary version: {output!r}")
            info = subprocess.run([str(extracted), "info", str(SMOKE_EXR)], cwd=directory,
                                  env=env, check=True, capture_output=True, text=True,
                                  timeout=30).stdout
            if "compression" not in info:
                raise RuntimeError(f"`exr-rs info` printed no header:\n{info}")
            print("Packaged binary: --version and info verified", flush=True)
    print(f"Release ZIP: {destination}", flush=True)
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("ci", "release"))
    parser.add_argument("--target", choices=TARGETS)
    args = parser.parse_args()
    host = rust_host()
    target = args.target or host
    if target not in TARGETS:
        parser.error(f"unsupported release host: {host}")
    # The packaged binary is run as a smoke test, so the target must be the host.
    if target != host:
        parser.error(f"{target} requires a native runner, got {host}")

    manifest = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))
    version = manifest["package"]["version"]
    # `version.workspace = true`: the value lives in [workspace.package].
    if not isinstance(version, str):
        version = manifest["workspace"]["package"]["version"]
    if os.environ.get("GITHUB_REF_TYPE") == "tag":
        tag = os.environ.get("GITHUB_REF_NAME")
        if tag != f"v{version}":
            parser.error(f"release tag {tag!r} must match Cargo.toml: v{version}")

    env = build_env(target)
    common = ["--locked", "--workspace", "--target", target]
    if args.command == "ci":
        run(["cargo", "clippy", *common, "--all-targets", "--", "-D", "warnings"], env)
        # openexr-py is outside the workspace with its own Cargo.lock: check it on every
        # push, or a stale lock only shows when the wheels are built for a tag.
        run(["cargo", "clippy", "--locked", "--manifest-path", "crates/openexr-py/Cargo.toml",
             "--target", target, "--all-targets", "--", "-D", "warnings"], env)
        run(["cargo", "test", *common, "--no-fail-fast"], env)
    run(["cargo", "build", "--locked", "--target", target, "--release", "--bin", "exr-rs"], env)
    binary = Path(env["CARGO_TARGET_DIR"]) / target / "release" / (
        "exr-rs.exe" if "windows" in target else "exr-rs")
    verify_dependencies(binary, target)
    package(binary, target, version, licenses(target, env))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
