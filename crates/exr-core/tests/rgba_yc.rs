//! Integration test for the luminance-chroma read path (`RgbaInputFile`).
//!
//! `golden_yc.exr` and `golden_rgba.exr` are the SAME image written by the real
//! C++ `RgbaOutputFile` — once as luminance + half-resolution chroma
//! (`WRITE_YCA`: `Y` at 1x1, `RY`/`BY` at 2x2), once full-resolution RGBA.
//! Reconstructing the first must closely match the second (chroma subsampling
//! is lossy, so a small mean error is allowed) — a real end-to-end check of the
//! 27-tap reconstruction filters + YCA→RGBA + saturation fix against data a C++
//! encoder produced.
//!
//! This used to point at `openexr-images/Chromaticities/Rec709_YC.exr` and
//! silently `return`ed when it was absent — which it is in every checkout, so
//! the only end-to-end YCA test never ran once. The fixture is now generated by
//! the same C++ oracle as every other golden (`cargo run -p xtask -- parity-exr`).

use std::path::PathBuf;

use exr_core::rgba::RgbaInputFile;

mod support;

const HOW_TO_GET: &str =
    "Run `cargo run -p xtask -- parity-exr` to regenerate the C++ goldens.";

fn golden(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests").join("parity").join(name)
}

#[test]
fn yc_golden_reconstructs_close_to_rgb() {
    let name = "yc_golden_reconstructs_close_to_rgb";
    let Some(yc) = support::fixture_or_skip(name, golden("golden_yc.exr"), HOW_TO_GET) else {
        return;
    };
    let Some(rgb) = support::fixture_or_skip(name, golden("golden_rgba.exr"), HOW_TO_GET) else {
        return;
    };

    // Reconstruct the luminance-chroma file to full-resolution RGBA.
    let recon = RgbaInputFile::read(&yc).expect("read golden_yc.exr");
    let (w, h) = (recon.width(), recon.height());
    assert!(w > 0 && h > 0, "empty image");
    assert_eq!(recon.pixels.len(), w * h);
    assert!(
        recon.pixels.iter().all(|p| p.r.to_f32().is_finite()
            && p.g.to_f32().is_finite()
            && p.b.to_f32().is_finite()),
        "reconstructed pixels must be finite"
    );

    // Reference full RGB.
    let reference = exr_core::read(&rgb).expect("read golden_rgba.exr");
    assert_eq!(reference.width() as usize, w);
    assert_eq!(reference.height() as usize, h);

    let get = |ch: &str| -> Vec<f32> {
        match reference.channel(ch) {
            Some(exr_core::ChannelData::Half(v)) => v.iter().map(|x| x.to_f32()).collect(),
            Some(exr_core::ChannelData::Float(v)) => v.clone(),
            _ => Vec::new(),
        }
    };
    let (rr, rg, rb) = (get("R"), get("G"), get("B"));
    assert_eq!(
        rr.len(),
        w * h,
        "golden_rgba.exr must expose R/G/B planes (else the MAE below is never computed)"
    );

    // Mean absolute error over all RGB samples.
    let mut sum = 0.0f64;
    let mut worst = 0.0f32;
    for i in 0..w * h {
        let p = &recon.pixels[i];
        for (got, want) in [(p.r.to_f32(), rr[i]), (p.g.to_f32(), rg[i]), (p.b.to_f32(), rb[i])] {
            let d = (got - want).abs();
            sum += d as f64;
            worst = worst.max(d);
        }
    }
    let mae = sum / (3.0 * (w * h) as f64);
    eprintln!("YCA reconstruction MAE = {mae:.5} (worst {worst:.5}) over {w}x{h}");
    assert!(mae < 0.02, "reconstruction MAE {mae} too large (filters wrong?)");
    // A tolerance that only bounds the mean would pass on a filter that is
    // catastrophically wrong in a few pixels; bound the worst sample too.
    assert!(worst < 0.15, "worst-case reconstruction error {worst} too large");
}

/// Parse `oracle.cpp`'s `rgba-read <path> <out>` binary dump: `u32 width, u32
/// height` (LE), then `width*height` pixels row-major, each 4x `u16` LE (r,
/// g, b, a half bits) — see `oracle.cpp`'s `do_rgba_read` for the writer.
fn parse_rgba_dump(bytes: &[u8]) -> (u32, u32, Vec<[u16; 4]>) {
    let w = u32::from_le_bytes(bytes[0..4].try_into().unwrap());
    let h = u32::from_le_bytes(bytes[4..8].try_into().unwrap());
    let mut pixels = Vec::with_capacity((w * h) as usize);
    let mut off = 8usize;
    for _ in 0..(w * h) {
        let mut p = [0u16; 4];
        for slot in &mut p {
            *slot = u16::from_le_bytes(bytes[off..off + 2].try_into().unwrap());
            off += 2;
        }
        pixels.push(p);
    }
    assert_eq!(off, bytes.len(), "dump has trailing/missing bytes");
    (w, h, pixels)
}

/// BIT-EXACT check of `exr_core::rgba::RgbaInputFile` against a committed C++
/// `Imf::RgbaInputFile` decode dump (`oracle.cpp`'s `rgba-read` mode,
/// `xtask::DECODE_DUMPS`). Unlike `yc_golden_reconstructs_close_to_rgb`
/// (which only bounds the error against an INDEPENDENT full-res reference —
/// chroma subsampling is genuinely lossy, so "close" is the right and only
/// claim there), this asserts IDENTICAL bits: the reference here is what the
/// SAME reconstruction algorithm, run by the real C++ implementation,
/// produces from the SAME encoded bytes. `golden_rgba.exr` additionally
/// proves the plain-RGBA path bit-exact, since its decode has no
/// lossy step at all.
#[test]
fn rgba_input_file_matches_cpp_rgba_input_file_bit_exact() {
    for golden_name in ["golden_yc.exr", "golden_rgba.exr"] {
        let name = "rgba_input_file_matches_cpp_rgba_input_file_bit_exact";
        let golden = golden(golden_name);
        let dump_path = PathBuf::from(format!("{}.dump", golden.display()));
        let Some(dump_path) = support::fixture_or_skip(name, dump_path, HOW_TO_GET) else {
            return;
        };
        let Some(golden) = support::fixture_or_skip(name, golden, HOW_TO_GET) else {
            return;
        };

        let dump_bytes = std::fs::read(&dump_path)
            .unwrap_or_else(|e| panic!("read {}: {e}", dump_path.display()));
        let (dw, dh, expected) = parse_rgba_dump(&dump_bytes);

        let ours = RgbaInputFile::read(&golden)
            .unwrap_or_else(|e| panic!("RgbaInputFile::read({golden_name}): {e}"));
        assert_eq!(ours.width() as u32, dw, "{golden_name}: width mismatch vs C++ dump");
        assert_eq!(ours.height() as u32, dh, "{golden_name}: height mismatch vs C++ dump");
        assert_eq!(ours.pixels.len(), expected.len(), "{golden_name}: pixel count mismatch");

        let mut mismatches = 0usize;
        for (i, (p, want)) in ours.pixels.iter().zip(expected.iter()).enumerate() {
            let got = [p.r.bits(), p.g.bits(), p.b.bits(), p.a.bits()];
            if got != *want {
                if mismatches < 5 {
                    let x = i % dw as usize;
                    let y = i / dw as usize;
                    eprintln!(
                        "{golden_name}: mismatch at ({x},{y}): ours={got:04x?} cpp={want:04x?}"
                    );
                }
                mismatches += 1;
            }
        }
        assert_eq!(
            mismatches, 0,
            "{golden_name}: {mismatches}/{} pixels differ from the C++ RgbaInputFile decode",
            expected.len()
        );
    }
}

const YCW: usize = 64;
const YCH: usize = 48;

fn yc_gradient_pixels() -> Vec<exr_core::rgba::Rgba> {
    use exr_core::rgba::Rgba;
    use imath_rs::Half;

    let mut pixels = vec![Rgba::default(); YCW * YCH];
    for y in 0..YCH {
        for x in 0..YCW {
            let r = x as f32 / (YCW - 1) as f32;
            let g = y as f32 / (YCH - 1) as f32;
            let b = 0.5 * ((x + y) as f32 / (YCW + YCH - 2) as f32);
            pixels[y * YCW + x] =
                Rgba::new(Half::from_f32(r), Half::from_f32(g), Half::from_f32(b), Half::from_f32(1.0));
        }
    }
    pixels
}

fn yc_header() -> exr_core::header::Header {
    use exr_core::attr::{Compression, LineOrder};
    use exr_core::header::Header;
    use imath_rs::V2f;

    Header::with_dimensions(
        YCW as i32,
        YCH as i32,
        1.0,
        V2f { x: 0.0, y: 0.0 },
        1.0,
        LineOrder::IncreasingY,
        Compression::Zip,
    )
    .expect("build header")
}

fn assert_byte_exact(golden_name: &str, ours: &[u8], expected: &[u8], detail: &str) {
    assert_eq!(
        ours.len(),
        expected.len(),
        "{golden_name} ({detail}): length differs (ours {} vs cpp {})",
        ours.len(),
        expected.len()
    );
    if ours != expected {
        let first_diff = ours.iter().zip(expected.iter()).position(|(a, b)| a != b).unwrap();
        panic!(
            "{golden_name} ({detail}): byte mismatch at offset {first_diff} (ours {:#04x} vs cpp {:#04x})",
            ours[first_diff], expected[first_diff]
        );
    }
}

/// BYTE-EXACT check of `exr_core::rgba::RgbaOutputFile` against `golden_yc.exr`
/// / `golden_rgba.exr` — the real C++ `RgbaOutputFile`'s own output, from the
/// exact same source pixels (`oracle.cpp`'s `yc_pixel` gradient formula,
/// `do_write_rgba`). Covers both the YCA path (`WRITE_YCA`: filtering,
/// subsampling and `roundYCA`) and the plain path (`WRITE_RGBA`: direct
/// R/G/B/A, no conversion) via the one-shot `write_stream` convenience.
#[test]
fn rgba_output_file_matches_cpp_rgba_output_file_byte_exact() {
    use exr_core::io::MemOStream;
    use exr_core::rgba::RgbaChannels;
    use exr_core::rgba::RgbaOutputFile;

    let pixels = yc_gradient_pixels();
    for (golden_name, chans) in
        [("golden_yc.exr", RgbaChannels::WRITE_YCA), ("golden_rgba.exr", RgbaChannels::WRITE_RGBA)]
    {
        let name = "rgba_output_file_matches_cpp_rgba_output_file_byte_exact";
        let Some(golden_path) = support::fixture_or_skip(name, golden(golden_name), HOW_TO_GET) else {
            return;
        };
        let expected = std::fs::read(&golden_path).unwrap_or_else(|e| panic!("read {golden_name}: {e}"));

        let header = yc_header();
        let mut out = MemOStream::new();
        RgbaOutputFile::write_stream(&mut out, &header, chans, &pixels)
            .unwrap_or_else(|e| panic!("write {golden_name}: {e}"));
        assert_byte_exact(golden_name, &out.into_data(), &expected, "one-shot write_stream");
    }
}

/// Same byte-exact check, but driving [`RgbaOutputFile::write_pixels`]
/// STREAMING, in strips of 1, 7 and 48 (= the whole image) lines — proving
/// the ring-buffer port produces IDENTICAL output regardless of how the
/// caller chunks its writes (the strip-writing use case at 16k-65k: a
/// 65536-row image is never materialised, only fed a strip at a time).
#[test]
fn rgba_output_file_streaming_strips_match_cpp_byte_exact() {
    use exr_core::io::MemOStream;
    use exr_core::rgba::{RgbaChannels, RgbaOutputFile};

    let pixels = yc_gradient_pixels();
    for (golden_name, chans) in
        [("golden_yc.exr", RgbaChannels::WRITE_YCA), ("golden_rgba.exr", RgbaChannels::WRITE_RGBA)]
    {
        let name = "rgba_output_file_streaming_strips_match_cpp_byte_exact";
        let Some(golden_path) = support::fixture_or_skip(name, golden(golden_name), HOW_TO_GET) else {
            return;
        };
        let expected = std::fs::read(&golden_path).unwrap_or_else(|e| panic!("read {golden_name}: {e}"));

        for strip in [1usize, 7, YCH] {
            let header = yc_header();
            let mut out = MemOStream::new();
            {
                let mut f = RgbaOutputFile::new(&mut out, &header, chans).unwrap_or_else(|e| {
                    panic!("{golden_name} (strip {strip}): RgbaOutputFile::new: {e}")
                });
                f.set_frame_buffer(1, YCW as isize).unwrap();
                let mut y = 0usize;
                while y < YCH {
                    let n = strip.min(YCH - y);
                    let rows = &pixels[y * YCW..(y + n) * YCW];
                    f.write_pixels(rows, n as i32).unwrap_or_else(|e| {
                        panic!("{golden_name} (strip {strip}, y={y}, n={n}): write_pixels: {e}")
                    });
                    y += n;
                }
            }
            assert_byte_exact(golden_name, &out.into_data(), &expected, &format!("strip {strip}"));
        }
    }
}

/// `setYCRounding` must actually change the written bits on the YCA path —
/// otherwise a silently-ignored rounding setting would pass every other
/// test here undetected.
#[test]
fn rgba_output_file_set_yc_rounding_changes_output() {
    use exr_core::io::MemOStream;
    use exr_core::rgba::{RgbaChannels, RgbaOutputFile};

    let pixels = yc_gradient_pixels();
    let header = yc_header();

    let default_bytes = {
        let mut out = MemOStream::new();
        RgbaOutputFile::write_stream(&mut out, &header, RgbaChannels::WRITE_YCA, &pixels).unwrap();
        out.into_data()
    };

    let custom_bytes = {
        let mut out = MemOStream::new();
        {
            let mut f = RgbaOutputFile::new(&mut out, &header, RgbaChannels::WRITE_YCA).unwrap();
            f.set_yc_rounding(3, 2); // far from the default (7, 5)
            f.set_frame_buffer(1, YCW as isize).unwrap();
            f.write_pixels(&pixels, YCH as i32).unwrap();
        }
        out.into_data()
    };

    assert_ne!(
        default_bytes, custom_bytes,
        "set_yc_rounding(3, 2) must change the written bits vs the default (7, 5)"
    );
}

/// BIT-EXACT check of `set_yc_rounding` against the real C++
/// `RgbaOutputFile::setYCRounding` — `golden_yc_rounded.exr`
/// (`oracle.cpp`'s `write-yc-rounded` mode, `roundY=3, roundC=2`, otherwise
/// identical to `golden_yc.exr`). Closes the gap
/// `rgba_output_file_set_yc_rounding_changes_output` leaves open (that test
/// only proves rounding changes OUR OWN output, not that it matches C++'s).
#[test]
fn rgba_output_file_set_yc_rounding_matches_cpp_byte_exact() {
    use exr_core::io::MemOStream;
    use exr_core::rgba::{RgbaChannels, RgbaOutputFile};

    let name = "rgba_output_file_set_yc_rounding_matches_cpp_byte_exact";
    let Some(golden_path) = support::fixture_or_skip(name, golden("golden_yc_rounded.exr"), HOW_TO_GET) else {
        return;
    };
    let expected = std::fs::read(&golden_path).unwrap_or_else(|e| panic!("read golden_yc_rounded.exr: {e}"));

    let pixels = yc_gradient_pixels();
    let header = yc_header();
    let mut out = MemOStream::new();
    {
        let mut f = RgbaOutputFile::new(&mut out, &header, RgbaChannels::WRITE_YCA).unwrap();
        f.set_yc_rounding(3, 2);
        f.set_frame_buffer(1, YCW as isize).unwrap();
        f.write_pixels(&pixels, YCH as i32).unwrap();
    }
    assert_byte_exact("golden_yc_rounded.exr", &out.into_data(), &expected, "set_yc_rounding(3, 2)");
}
