/// What the command line asks for.
enum Cmd {
    Help,
    Version,
    /// A file name is missing: the C++ prints the usage line and exits -1.
    Usage,
    Make(Box<Job>),
}

/// Everything `main` collects from the command line.
struct Job {
    input: String,
    output: String,
    /// The type of map to produce.
    ty: Envmap,
    /// `-ci` / `-li`: the input's type regardless of its `envmap` attribute.
    over: Option<Envmap>,
    /// `-p`: extra lines above and below a lat-long input, as fractions of its height.
    pad: (f32, f32),
    /// `-b`.
    blur: bool,
    opts: Opts,
}

/// `main`'s argument loop: left to right, the first error wins, `-h` / `--version` act when reached.
fn parse(argv: &[String]) -> Result<Cmd, String> {
    let (mut input, mut output): (Option<&str>, Option<&str>) = (None, None);
    let mut job = Job {
        input: String::new(),
        output: String::new(),
        ty: Envmap::Cube,
        over: None,
        pad: (0.0, 0.0),
        blur: false,
        opts: Opts {
            tile: (64, 64),
            mode: LevelMode::OneLevel,
            rounding: LevelRoundingMode::RoundDown,
            comp: Compression::Zip,
            width: 256,
            radius: 1.0,
            samples: 5,
            verbose: false,
        },
    };
    let mut only_files = false;
    let mut i = 0;
    while i < argv.len() {
        let tok = argv[i].as_str();
        let mut used = 1;
        if only_files || !tok.starts_with('-') || tok == "-" {
            // The first name is the input, a later one the output (a third replaces the second).
            if input.is_none() {
                input = Some(tok);
            } else {
                output = Some(tok);
            }
            i += 1;
            continue;
        }
        match tok {
            "--" => only_files = true,
            "-o" => job.opts.mode = LevelMode::OneLevel,
            "-m" => job.opts.mode = LevelMode::MipmapLevels,
            "-c" => job.ty = Envmap::Cube,
            "-l" => job.ty = Envmap::LatLong,
            "-ci" => job.over = Some(Envmap::Cube),
            "-li" => job.over = Some(Envmap::LatLong),
            "-w" => {
                let v = values(argv, i, 1, "Missing width for -w argument")?;
                job.opts.width = c_int(&v[0])?;
                if job.opts.width <= 0 {
                    return Err("Output image width must be greater than zero".into());
                }
                used = 2;
            }
            "-f" => {
                let v = values(argv, i, 2, "Missing filter radius with -f option")?;
                job.opts.radius = c_f32(&v[0])?;
                job.opts.samples = c_int(&v[1])?;
                if job.opts.radius < 0.0 {
                    return Err("Filter radius must not be less than zero".into());
                }
                if job.opts.samples <= 0 {
                    return Err("Sampling rate must be greater than zero".into());
                }
                used = 3;
            }
            "-b" => job.blur = true,
            "-t" => {
                let v = values(argv, i, 2, "missing tile size with -t option")?;
                let (x, y) = (c_int(&v[0])?, c_int(&v[1])?);
                if x <= 0 || y <= 0 {
                    return Err("Tile size must be greater than zero".into());
                }
                job.opts.tile = (x as u32, y as u32);
                used = 3;
            }
            "-p" => {
                let v = values(argv, i, 2, "missing padding value with -p option")?;
                job.pad = (c_f32(&v[0])?, c_f32(&v[1])?);
                if job.pad.0 < 0.0 || job.pad.1 < 0.0 {
                    return Err("Padding must not be less than zero".into());
                }
                used = 3;
            }
            "-d" => job.opts.rounding = LevelRoundingMode::RoundDown,
            "-u" => job.opts.rounding = LevelRoundingMode::RoundUp,
            "-z" => {
                job.opts.comp = get_compression(&values(argv, i, 1, "Missing compression method with -z option")?[0])?;
                used = 2;
            }
            "-v" => job.opts.verbose = true,
            "-h" | "--help" => return Ok(Cmd::Help),
            "--version" => return Ok(Cmd::Version),
            _ => return Err(format!("Unknown option {tok}")),
        }
        i += used;
    }
    let (Some(input), Some(output)) = (input, output) else { return Ok(Cmd::Usage) };
    job.input = input.into();
    job.output = output.into();
    Ok(Cmd::Make(Box::new(job)))
}

/// Run `envmap`: parse, then read, optionally blur, and write.
pub fn run(args: Args, verbose: bool) -> CliResult {
    match parse(&args.args).map_err(CliError::Other)? {
        Cmd::Help => print_help("envmap"),
        Cmd::Version => {
            super::print_version("exrenvmap");
            Ok(())
        }
        Cmd::Usage => {
            errln!("Usage: exr-rs envmap [options] infile outfile");
            Err(CliError::Exit(-1))
        }
        Cmd::Make(mut job) => {
            job.opts.verbose |= verbose;
            make(&job)
        }
    }
}

/// `main`'s tail: load `infile`, convert it, save the result in `outfile`.
fn make(job: &Job) -> CliResult {
    let verbose = job.opts.verbose;
    let mut image = EnvmapImage::new();
    let input = read::read_input(&job.input, job.pad, job.over, verbose, &mut image)?;
    if job.blur {
        blur::blur(&mut image, verbose)?;
    }
    match job.ty {
        Envmap::Cube => make_cube(&mut image, input.header, input.channels, &job.output, &job.opts)?,
        Envmap::LatLong => make_ll(&mut image, input.header, input.channels, &job.output, &job.opts)?,
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args(line: &str) -> Vec<String> {
        line.split_whitespace().map(String::from).collect()
    }

    fn job(line: &str) -> Job {
        match parse(&args(line)) {
            Ok(Cmd::Make(j)) => *j,
            Ok(_) => panic!("not a job: {line}"),
            Err(e) => panic!("{line}: {e}"),
        }
    }

    fn err(line: &str) -> String {
        match parse(&args(line)) {
            Err(e) => e,
            Ok(_) => panic!("{line} parsed"),
        }
    }

    #[test]
    fn defaults_are_the_cpp_ones() {
        let j = job("in.exr out.exr");
        assert_eq!((j.input.as_str(), j.output.as_str()), ("in.exr", "out.exr"));
        assert_eq!((j.ty, j.over, j.pad, j.blur), (Envmap::Cube, None, (0.0, 0.0), false));
        let o = j.opts;
        assert_eq!((o.mode, o.rounding, o.comp, o.tile), (LevelMode::OneLevel, LevelRoundingMode::RoundDown, Compression::Zip, (64, 64)));
        assert_eq!((o.width, o.radius, o.samples, o.verbose), (256, 1.0, 5, false));
    }

    #[test]
    fn the_last_of_competing_options_wins() {
        assert_eq!(job("-m -o a b").opts.mode, LevelMode::OneLevel);
        assert_eq!(job("-o -m a b").opts.mode, LevelMode::MipmapLevels);
        assert_eq!(job("-c -l a b").ty, Envmap::LatLong);
        assert_eq!(job("-l -c a b").ty, Envmap::Cube);
        assert_eq!(job("-ci -li a b").over, Some(Envmap::LatLong));
        assert_eq!(job("-u -d a b").opts.rounding, LevelRoundingMode::RoundDown);
        assert_eq!(job("a -m b").opts.mode, LevelMode::MipmapLevels, "options may follow the files");
    }

    #[test]
    fn options_with_values() {
        let j = job("-w 0x200 -f 1.5 7 -t 32 16 -p 0.25 .5 -z PIZ -u -b -v a b");
        assert_eq!((j.opts.width, j.opts.radius, j.opts.samples, j.opts.tile), (512, 1.5, 7, (32, 16)));
        assert_eq!((j.pad, j.opts.comp, j.opts.rounding, j.blur, j.opts.verbose), ((0.25, 0.5), Compression::Piz, LevelRoundingMode::RoundUp, true, true));
        // A third name replaces the output.
        assert_eq!(job("a b c").output, "c");
    }

    #[test]
    fn the_cpp_error_messages() {
        assert_eq!(err("-w"), "Missing width for -w argument");
        assert_eq!(err("-w 0 a b"), "Output image width must be greater than zero");
        assert_eq!(err("-w -4 a b"), "Output image width must be greater than zero");
        assert_eq!(err("a b -f 1"), "Missing filter radius with -f option");
        assert_eq!(err("-f -1 5 a b"), "Filter radius must not be less than zero");
        assert_eq!(err("-f 1 0 a b"), "Sampling rate must be greater than zero");
        assert_eq!(err("-t 8"), "missing tile size with -t option");
        assert_eq!(err("-t 0 8 a b"), "Tile size must be greater than zero");
        assert_eq!(err("-p 1"), "missing padding value with -p option");
        assert_eq!(err("-p 1 -1 a b"), "Padding must not be less than zero");
        assert_eq!(err("-z"), "Missing compression method with -z option");
        assert_eq!(err("-z lzw a b"), "Unknown compression method \"lzw\"");
        assert_eq!(err("-x a b"), "Unknown option -x");
        assert_eq!(err("-w x a b"), "Expected an integer, got \"x\"");
        assert_eq!(err("-f x 5 a b"), "Expected a number, got \"x\"");
    }

    #[test]
    fn help_version_and_usage_act_where_they_are_met() {
        assert!(matches!(parse(&args("a b --version")), Ok(Cmd::Version)));
        assert!(matches!(parse(&args("-m -h")), Ok(Cmd::Help)));
        assert!(matches!(parse(&args("a")), Ok(Cmd::Usage)));
        assert!(matches!(parse(&args("-m")), Ok(Cmd::Usage)));
        // An earlier error wins over a later -h.
        assert_eq!(err("-w 0 -h"), "Output image width must be greater than zero");
        // `--` ends the options: what follows is a file name.
        assert_eq!(job("-- -a b").input, "-a");
    }

    #[test]
    fn the_help_lists_every_option_and_codec() {
        let h = help();
        for opt in ["-o ", "-m ", "-c ", "-l ", "-ci ", "-li ", "-w x", "-f r n", "-b ", "-t x y", "-p t b", "-d ", "-u ", "-z x", "-v ", "-h, --help", "--version"] {
            assert!(h.contains(opt), "help lacks {opt}");
        }
        for c in Compression::ALL {
            assert!(h.contains(c.name()), "help lacks {}", c.name());
        }
    }
}
