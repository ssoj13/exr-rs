pub const EXAMPLES: &str = examples!(
    "exr-rs envmap latlong.exr cube.exr            # lat-long -> cube-face map, 256 pixel faces",
    "exr-rs envmap -l cube.exr latlong.exr         # cube-face -> lat-long map, 256 x 128",
    "exr-rs envmap -m -w 512 latlong.exr cube.exr  # MIP-mapped, 512 pixel faces",
    "exr-rs envmap -b latlong.exr diffuse.exr      # diffuse blur (an irradiance map)",
    "exr-rs envmap latlong.exr cube_%.exr          # six files cube_+X.exr ... cube_-Z.exr",
);

/// `envmap` arguments: the tool has its own grammar ([`parse`]), so clap only hands over the words
/// and shows the option reference as the help of this argument.
#[derive(clap::Args)]
#[command(
    disable_help_flag = true,
    allow_hyphen_values = true,
    override_usage = "exr-rs envmap [options] <infile> <outfile>"
)]
pub struct Args {
    #[arg(value_name = "ARGS", required = true, trailing_var_arg = true, allow_hyphen_values = true, help = help())]
    args: Vec<String>,
}

