//! `exr-rs envmap` — port of OpenEXR's `exrenvmap` (`openexr/src/bin/exrenvmap`, v3.4.15):
//! convert a lat-long environment map to a cube-face one or back, resample it (`-w`, `-f`), blur it
//! diffusely (`-b`), write levels (`-m`) and tiles (`-t`). This file is `main.cpp` (the command
//! line); the rest mirrors the C++ files: `image` (`EnvmapImage`), `resize` (`resizeImage`), `blur`
//! (`blurImage`), `read` (`readInputImage`) and `make` (`makeCubeMap` + `makeLatLongMap`, which are
//! one function here). The direction <-> pixel geometry (`ImfEnvmap`) is
//! `exr_core::attr::envmap`.
//!
//! Options are the tool's single-dash ones (`-w 512`, `-f 1.5 7`), parsed left to right like the
//! C++. Deliberate differences from `main.cpp` and the files it calls, each a defect there:
//! * an unknown `-option` is an error (the C++ takes it for a file name); `--` ends the options;
//! * a number that is not entirely a number, or does not fit an `int`, is an error naming it where
//!   `strtol` / `strtod` would read a prefix, 0 or saturate;
//! * without arguments the project convention applies (help on stdout, exit 0), not usage on stderr
//!   with exit -1; `-h` prints the clap-rendered option reference, not the C++ text;
//! * `-v` is the global `exr-rs -v` as well (it is accepted anywhere, as the C++ flag is): the
//!   messages appear when the log level is `debug` or finer, or when the tool's own `-v` was given;
//! * sizes that overflow `int` or cannot be allocated are errors (`bad_alloc` or undefined
//!   behaviour in the C++); the input is read in bands (`read`) and the blur computes each input
//!   direction once (`blur`), with the same bytes as a result.
//!
//! Kept from the C++: a missing file name prints the one-line usage on stderr and exits -1; the
//! output file is opened before anything is resampled, so a failure then leaves it behind.

